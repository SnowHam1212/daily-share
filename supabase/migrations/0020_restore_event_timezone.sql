-- ============================================================
-- 0020_restore_event_timezone.sql
-- events.timezone 列を本番に作り直す（バグ修正）
--
-- 症状:
--   予定の追加・編集が全ユーザーで失敗し、
--   「Could not find the 'timezone' column of 'events' in the schema cache」
--   が返る。CalendarTab の保存値は insert / update とも必ず timezone を
--   含むため、公開範囲・終日・繰り返しに関係なく全滅する。
--   閲覧（select *）と削除は列名を指定しないので動いてしまい、
--   「予定は見えるのに追加も編集もできない」状態になる。
--
-- 経緯:
--   0008_event_timezone.sql は列を追加しているが、本番には列が無かった。
--   0008 という番号が harden_definer_functions（現 0014）と重複しており、
--   Supabase の履歴テーブルはバージョン番号を主キーにするため
--   片方しか記録できない。結果 0008 は「適用済み」と判定され、
--   db push でも永久にスキップされる状態になっていた。
--   （番号重複自体は 0013 / 0014 へのリナンバーで解消済みだが、
--     すでに履歴へ記録された 0008 は再適用されないため、
--     新しい番号で入れ直す必要がある。）
--
--   同じ事故で 0007_join_team_by_code も本番に入っておらず、
--   0015_restore_join_team_by_code.sql で入れ直した。本ファイルは
--   その取りこぼしだった 2 件目にあたる。
--
-- 安全性:
--   nullable な列の追加のみで、既存行・既存コードを壊さない。
--   フロントは既にこの列がある前提でデプロイ済みのため、
--   適用しない限り不具合は解消しない。
-- ============================================================

ALTER TABLE events ADD COLUMN IF NOT EXISTS timezone text;
